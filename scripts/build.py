#!/usr/bin/env python3
"""Generate README.md from data/events.json.

Usage:
    python3 scripts/build.py          # rewrite README.md
    python3 scripts/build.py --check  # exit 1 if README.md is out of date

Status is computed against the "as_of" date stored in the data file, so the
output is deterministic. Bump "as_of" whenever you update the data.
"""
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "events.json"
README = ROOT / "README.md"

SOURCE_ICON = {"official": "✅", "listing": "📋", "pattern": "🔁"}
REQUIRED = ["name", "host", "where", "when", "apply", "url", "source"]


def validate(data):
    errors = []
    for section, rows in data.items():
        if section == "as_of":
            continue
        for row in rows:
            label = "%s / %s" % (section, row.get("name", "?"))
            for key in REQUIRED:
                if not row.get(key):
                    errors.append("%s: missing %s" % (label, key))
            if row.get("source") not in SOURCE_ICON:
                errors.append("%s: source must be one of %s" % (label, sorted(SOURCE_ICON)))
            for key in ("start", "deadline"):
                if row.get(key):
                    try:
                        date.fromisoformat(row[key])
                    except ValueError:
                        errors.append("%s: %s is not YYYY-MM-DD" % (label, key))
            if not row["url"].startswith("https://"):
                errors.append("%s: url must be https" % label)
    return errors


def status(row, today):
    deadline = date.fromisoformat(row["deadline"]) if row.get("deadline") else None
    start = date.fromisoformat(row["start"]) if row.get("start") else None
    if deadline and deadline >= today:
        return "🟢 Deadline ahead"
    if start and start >= today:
        return "🟡 Upcoming"
    if start or deadline:
        return "⚪ Next cycle"
    return "🔵 Recurring"


def cell(text):
    return str(text or "—").replace("|", "\\|").replace("\n", " ")


def sort_key(row, today):
    start = date.fromisoformat(row["start"]) if row.get("start") else None
    if start and start >= today:
        return (0, start.toordinal())
    if not start:
        return (1, 0)
    return (2, -start.toordinal())


def table(rows, today, sort=True):
    if sort:
        rows = sorted(rows, key=lambda r: sort_key(r, today))
    out = [
        "| Event | Host | When | Where | Applying | Size & perks | Status | Src |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        perks = " · ".join(x for x in (r.get("size"), r.get("perks")) if x)
        name = "[%s](%s)" % (cell(r["name"]), r["url"])
        if r.get("notes"):
            name += "<br><sub>%s</sub>" % cell(r["notes"])
        out.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            name, cell(r["host"]), cell(r["when"]), cell(r["where"]),
            cell(r["apply"]), cell(perks), status(r, today), SOURCE_ICON[r["source"]],
        ))
    return "\n".join(out)


def deadlines(data, today):
    rows = []
    for section, items in data.items():
        if section == "as_of":
            continue
        for r in items:
            if r.get("deadline") and date.fromisoformat(r["deadline"]) >= today:
                rows.append(r)
    rows.sort(key=lambda r: r["deadline"])
    out = ["| Deadline | Event | When | Details |", "|---|---|---|---|"]
    for r in rows:
        d = date.fromisoformat(r["deadline"])
        out.append("| **%s** | [%s](%s) | %s | %s |" % (
            d.strftime("%b %-d, %Y"), cell(r["name"]), r["url"], cell(r["when"]), cell(r["apply"])))
    return "\n".join(out)


def render(data):
    today = date.fromisoformat(data["as_of"])
    cats = []
    for r in data["competitions"]:
        if r["category"] not in cats:
            cats.append(r["category"])
    comp = []
    for c in cats:
        comp.append("### %s\n\n%s" % (c, table([r for r in data["competitions"] if r["category"] == c], today)))

    total = sum(len(v) for k, v in data.items() if k != "as_of")
    return """<!-- GENERATED by scripts/build.py from data/events.json. Edit the data, not this file. -->
# Hackathon Atlas

A curated list of **collegiate hackathons** (split by 36-hour and 24-hour formats), **company-run hackathons you can apply to**, and **tech competitions** for university students — plus a [playbook](docs/PLAYBOOK.md) of how applications, travel money and judging actually work.

**{total} entries · data as of {as_of}.** Dates move; always confirm on the event's own site before booking anything.

## How to read this

| Mark | Meaning |
|---|---|
| ✅ | Dates read from the event's own site, the MLH season page, or Devpost on the as-of date |
| 📋 | Taken from a third-party listing or job board; likely right, not confirmed at the source |
| 🔁 | Recurring event; timing is the historical pattern, this cycle's dates aren't posted yet |
| 🟢 / 🟡 / ⚪ / 🔵 | Deadline still ahead / event upcoming / already held this cycle / recurring or rolling |

## Deadlines coming up

{deadlines}

## Collegiate hackathons: 36-hour

Friday-evening-to-Sunday events. These are the big travel hackathons; most are application-based and many reimburse travel.

{t36}

## Collegiate hackathons: 24-hour

Saturday-to-Sunday events. Easier to fit around classes, and usually easier to get into.

{t24}

## Company and big-tech hackathons

Events run by companies or labs rather than student organisers. Several double as recruiting pipelines.

{company}

## Tech competitions

{comp}

## The short version of the playbook

- **Deadlines are far earlier than the events.** HackMIT closes around July 4 for a September event; Cal Hacks closes mid-September for October; PennApps priority closes two months ahead.
- **Priority deadlines decide travel money.** HackUTD says so outright: priority applicants get first consideration for reimbursement and early sponsor interviews.
- **Sponsor tracks repeat across events.** Capital One's "Best Use of Nessie" ($300 per team member) and Photon's messaging-agent track appeared at both HackUTD and HackHarvard in 2026. Learn a sponsor's API once and reuse it.
- **Some "hackathons" are interviews.** JPMorganChase Code for Good and the Citadel datathons feed straight into internship pipelines.
- **The AI-lab hackathons aren't on MLH.** They're announced on Cerebral Valley and Luma a few weeks out.

Full version: [docs/PLAYBOOK.md](docs/PLAYBOOK.md).

## Where this comes from

- [MLH 2027 season](https://www.mlh.com/seasons/2027/events) and [2026 season](https://www.mlh.com/seasons/2026/events) schedules
- Each event's official site and Devpost page (linked in the tables)
- [QuantVault's trading competition tracker](https://quantvault.org/quant-trading-competitions-2026.html) for the quant section
- Public job listings for company programmes
- Organiser and participant write-ups for the playbook

The "insider" material is community knowledge and what organisers publish about their own process. Nothing here is confidential, and reported acceptance numbers are secondhand unless an organiser published them.

## Contributing

Edit [`data/events.json`](data/events.json), run `python3 scripts/build.py`, and open a pull request. See [CONTRIBUTING.md](CONTRIBUTING.md).

## License

[MIT](LICENSE)
""".format(
        total=total,
        as_of=today.strftime("%B %-d, %Y"),
        deadlines=deadlines(data, today),
        t36=table(data["collegiate_36h"], today),
        t24=table(data["collegiate_24h"], today),
        company=table(data["company"], today),
        comp="\n\n".join(comp),
    )


def main():
    data = json.loads(DATA.read_text(encoding="utf-8"))
    errors = validate(data)
    if errors:
        print("\n".join(errors))
        return 1
    text = render(data)
    if "--check" in sys.argv:
        if README.read_text(encoding="utf-8") != text:
            print("README.md is out of date. Run: python3 scripts/build.py")
            return 1
        print("README.md is up to date.")
        return 0
    README.write_text(text, encoding="utf-8")
    print("Wrote README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
